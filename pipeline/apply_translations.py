def apply_translations(file_path):
    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()
    
    for block_id, translation in translations.items():
        # Pattern to find the specific block and its missing translation part
        # We need to be careful not to replace wrong things.
        # Structure: <section class="block paragraph" id="BLOCK_ID"> ... <p class="block-zh missing-trans">[Missing Translation]</p>
        
        # We search for the section with ID, then inside it, replace the missing-trans paragraph
        # Regex: (<section[^>]*id="BLOCK_ID"[^>]*>.*?)(<p class="block-zh missing-trans">.*?</p>)(.*?</section>)
        
        pattern = r'(<section[^>]*id="' + re.escape(block_id) + r'"[^>]*>.*?)(<p class="block-zh missing-trans">.*?</p>)(.*?</section>)'
        
        replacement = r'\1<p class="block-zh">' + translation + r'</p>\3'
        
        # Perform substitution
        new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
        if new_content != content:
            print(f"Applied translation for {block_id}")
            content = new_content
        else:
            print(f"Failed to apply translation for {block_id}")
        
    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(content)
    
    print("Translations applied successfully.")

if __name__ == "__main__":
    apply_translations('output/chapter5.html')
